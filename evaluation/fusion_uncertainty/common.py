# ----------------------------------------------------------------- case lists

def cases(split):
    if split in ATM:
        return sorted(os.listdir(ATM[split]["cache"]))
    if split in PED_GT_DIRS:
        out = []
        for f in sorted(glob.glob(os.path.join(PED_GT_DIRS[split], "*.nii.gz"))):
            m = re.search(r"(sub-\d+_acc-\d+)", os.path.basename(f))
            out.append(m.group(1))
        return out
    raise ValueError(split)


def ped_gt_path(cid, split="pediatric"):
    hits = glob.glob(os.path.join(PED_GT_DIRS[split], f"*{cid}*.nii.gz"))
    assert len(hits) == 1, (cid, hits)
    return hits[0]


def ped_case_dir(cid):
    hits = glob.glob(os.path.join(SEG_ROOT, "*", "*", cid))
    assert len(hits) == 1, (cid, hits)
    return hits[0]


# ----------------------------------------------------------------- loaders

def _aligned_gt(gt_path, ref_path):
    """GT drawn on the source scan, flipped onto the member masks' grid
    (bench_pediatric.aligned_gt, verbatim logic)."""
    g, r = sitk.ReadImage(gt_path), sitk.ReadImage(ref_path)
    if g.GetSize() != r.GetSize():
        raise ValueError(f"size {g.GetSize()} vs {r.GetSize()}")
    dg = np.array(g.GetDirection()).reshape(3, 3)
    dr = np.array(r.GetDirection()).reshape(3, 3)
    arr = sitk.GetArrayFromImage(g) > 0
    diff = np.diag(dg) / np.diag(dr)
    if not np.allclose(np.abs(dg), np.abs(dr)) or not np.allclose(np.abs(diff), 1):
        raise ValueError("unsupported direction change")
    for axis_sitk, s in enumerate(diff):
        if s < 0:
            arr = np.flip(arr, 2 - axis_sitk)
    return np.ascontiguousarray(arr)


def load_case(split, cid):
    c = {"split": split, "case": cid}
    if split in ATM:
        L = ATM[split]
        with open(os.path.join(L["cache"], cid, "meta.json")) as fh:
            meta = json.load(fh)
        label, _, spacing, _ = load_itk_image(os.path.join(L["labels"], cid + ".mha"))
        c["gt"] = (label > 0).astype(np.uint8)
        c["spacing"] = np.array(spacing, dtype=float)          # z, y, x
        skel = np.load(os.path.join(L["cache"], cid, "centerline.npy")).astype(np.uint8)
        skel = restore_image_via_box(tuple(meta["original_shape"]), skel, np.array(meta["bbox"]))
        c["gt_skeleton_raw"] = (skel > 0).astype(np.uint8)
        with np.load(os.path.join(L["airmorph"], f"ATM26_{cid}.npz")) as p:
            for k in AIRMORPH_MEMBERS:
                c[k] = p[k].astype(bool)
            c["airmorph"] = p["raw"].astype(bool)
        for k in ("medpseg", "tfenet"):
            with np.load(os.path.join(L[k], f"ATM26_{cid}.npz")) as p:
                c[k] = p["raw"].astype(bool)
    elif split in PED_GT_DIRS:
        d = ped_case_dir(cid)
        ref = os.path.join(d, "airway_bin.nii.gz")
        img = sitk.ReadImage(ref)
        c["spacing"] = np.array(img.GetSpacing()[::-1], dtype=float)
        c["gt"] = _aligned_gt(ped_gt_path(cid, split), ref).astype(np.uint8)
        c["airmorph"] = sitk.GetArrayFromImage(img) > 0
        for k, f in (("medpseg", "medpseg_airway.nii.gz"), ("tfenet", "tfenet_airway.nii.gz")):
            c[k] = sitk.GetArrayFromImage(sitk.ReadImage(os.path.join(d, f))) > 0
        with np.load(os.path.join(PED_MEMBERS, f"{cid}.npz")) as p:
            for k in AIRMORPH_MEMBERS:
                c[k] = p[k].astype(bool)
        skel_path = os.path.join(CACHE, split, cid, "gt_skeleton.npy")
        if os.path.exists(skel_path):
            c["gt_skeleton_raw"] = np.load(skel_path)
        else:
            from util.airwayatlas_utils import IMRAirwayAtlas_SkeletonExtraction
            skel = IMRAirwayAtlas_SkeletonExtraction(c["gt"], c["spacing"])
            c["gt_skeleton_raw"] = (np.asarray(skel) > 0).astype(np.uint8)
            os.makedirs(os.path.dirname(skel_path), exist_ok=True)
            np.save(skel_path, c["gt_skeleton_raw"])
    else:
        raise ValueError(split)
    for k in SEVEN + ["airmorph"]:
        assert c[k].shape == c["gt"].shape, (cid, k, c[k].shape, c["gt"].shape)
    c["gt_parsing"], c["gt_skeleton"] = parse_ground_truth(c["gt"], c["gt_skeleton_raw"])
    return c


# ----------------------------------------------------------------- fusion + metrics

def keep_seeded_component(mask, seed, connectivity=6):
    """The paper's component rule: the 6-connected component of `mask` holding
    most of `seed`; the largest when the seed misses every component."""
    st = ndimage.generate_binary_structure(3, 1 if connectivity == 6 else 3)
    lab, n = ndimage.label(mask.astype(bool), structure=st)
    if n == 0:
        return np.zeros(mask.shape, np.uint8)
    hit = np.bincount(lab[seed.astype(bool)], minlength=n + 1); hit[0] = 0
    if hit.sum() == 0:
        hit = np.bincount(lab.ravel(), minlength=n + 1); hit[0] = 0
    return (lab == int(hit.argmax())).astype(np.uint8)


def union_seeded(c):
    """The current method: union of the three, seeded component."""
    return keep_seeded_component(c["airmorph"] | c["medpseg"] | c["tfenet"], c["airmorph"])


def score(pred, c, cldice=True):
    """Verbatim metric set of training/evaluate.py (as in benchmark_adult/recompute.py).
    clDice skeletonises the prediction and dominates the run time; sweeps skip it."""
    pred = pred.astype(np.uint8); label = c["gt"]
    _, _, bnd = branch_detected_calculation(pred, c["gt_parsing"], c["gt_skeleton"], thresh=0.8)
    return {"DSC": float(dice_coefficient_score_calculation(pred, label)),
            "clDice": float(cldice_fixed(v_p_pred=pred, v_l_gt=label)) if cldice else float("nan"),
            "TLD": float(tree_length_calculation(pred, c["gt_skeleton"])),
            "BND": float(bnd),
            "Sensitivity": float(sensitivity_calculation(pred, label)),
            "Precision": float(precision_calculation(pred, label)),
            "FPR": float(false_positive_rate_calculation(pred, label))}


def confidence(c, scheme="model"):
    """Voxel confidence in [0, 1] from the seven binary members.

    model: each model one vote, AirMorph's vote graded by its own five members
           (mean of A5/5, MEDPSeg, TfeNet). This is the scheme the study uses.
    seven: plain fraction of the seven predictors.
    """
    a5 = np.zeros(c["gt"].shape, np.float32)
    for k in AIRMORPH_MEMBERS:
        a5 += c[k]
    if scheme == "model":
        return (a5 / 5.0 + c["medpseg"] + c["tfenet"]) / 3.0
    if scheme == "seven":
        return (a5 + c["medpseg"] + c["tfenet"]) / 7.0
    raise ValueError(scheme)


# ----------------------------------------------------------------- pattern calibration

def pattern_table(split):
    """P(airway | vote pattern) estimated on one split from the cached
    pattern histograms; pattern = AirMorph votes*4 + 2*MEDPSeg + TfeNet."""
    al = np.zeros(24); tp = np.zeros(24)
    for cid in cases(split):
        f = os.path.join(CACHE, split, cid, "pattern_hist.npz")
        if os.path.exists(f):
            h = np.load(f); al += h["all"]; tp += h["tp"]
    with np.errstate(invalid="ignore", divide="ignore"):
        p = np.where(al > 0, tp / np.maximum(al, 1), np.nan)
    return {"p": p, "n": al, "tp": tp}


def confidence_from_pattern(pattern, scheme="model", table=None):
    """Confidence map from the cached uint8 pattern volume (255 = outside)."""
    lut = np.zeros(256, np.float32)
    a5 = np.arange(24) // 4; md = (np.arange(24) // 2) % 2; tf = np.arange(24) % 2
    if scheme == "model":
        lut[:24] = (a5 / 5.0 + md + tf) / 3.0
    elif scheme == "seven":
        lut[:24] = (a5 + md + tf) / 7.0
    elif scheme == "calibrated":
        p = np.nan_to_num(table["p"], nan=0.5)
        lut[:24] = p
    else:
        raise ValueError(scheme)
    return lut[pattern]


def load_cached(split, cid):
    """A case rebuilt from the study cache alone (no member volumes)."""
    import pandas as pd
    d = os.path.join(CACHE, split, cid)
    v = np.load(os.path.join(d, "volumes.npz"))
    c = {"split": split, "case": cid, "gt": v["gt"], "gt_parsing": v["gt_parsing"].astype(np.int64),
         "gt_skeleton": v["gt_skeleton"], "spacing": v["spacing"], "pattern": v["pattern"],
         "dist": v["dist"].astype(np.float32), "airmorph": v["airmorph"].astype(bool),
         "medpseg": v["medpseg"].astype(bool), "tfenet": v["tfenet"].astype(bool)}
    c["M"] = c["pattern"] != 255
    c["tab"] = pd.read_csv(os.path.join(d, "branches.csv"))
    c["branch_map"] = np.load(os.path.join(d, "branch_map.npz"))["branch_map"]
    return c

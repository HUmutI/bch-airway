"""Paths, loaders and the metric wrapper shared by the fusion-uncertainty study.

Every absolute path has an izmir default and an AIRWAY_ROOT override. The study
reads the same stored member masks and ground truth as the rest of
`evaluation/`, so its numbers are commensurable with the paper's tables:

* ATM26 validation split: 30 cases, member masks regenerated on izmir
  (`ATM26_VAL_RUN/outputs/*/val_masks`), GT and cached TEASAR centrelines in
  `ATM26_VAL_RUN/data`.
* ATM26 test split: 30 cases, member masks from the original machine
  (`paper/airway_paper_bundle/08_masks_and_gt`).
* Pediatric: 9 expert-annotated cases; member masks from the cohort run in
  `airway-seg/`, AirMorph's five member votes re-generated by
  `rerun_airmorph_members.py`, GT in `pediatric_annotations/`.

A "case" is a dict with the seven binary member maps (`member_model1..3`,
`member_wingsnet`, `member_break`, `medpseg`, `tfenet`), the three model masks
the paper's fusion consumes (`airmorph`, `medpseg`, `tfenet`), the GT label,
the parsed GT (`gt_parsing`, `gt_skeleton`) and the voxel spacing (z, y, x, mm).

Run in the AirMorph environment (kimimaro, scikit-image, pandas).
"""
